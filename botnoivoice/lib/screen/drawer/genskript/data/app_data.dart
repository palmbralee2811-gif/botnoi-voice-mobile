class GenerationResult {
  final String script;
  final String? audioUrl;
  final List<dynamic>? scripts;

  GenerationResult({
    required this.script,
    this.audioUrl,
    this.scripts,
  });

  factory GenerationResult.fromJson(Map<String, dynamic> json) {
    String extractedText = "";

    // 1. ดึง List ของ scripts ออกมาอย่างปลอดภัย
    final List<dynamic>? scriptsList = json['scripts'] as List<dynamic>?;

    // 2. ตรวจสอบว่ามีข้อมูลใน List หรือไม่
    if (scriptsList != null && scriptsList.isNotEmpty) {
      final firstItem = scriptsList[0];

      if (firstItem is Map<String, dynamic>) {
        // --- จุดที่แก้ไข: เปลี่ยนจาก 'text' เป็น 'script' ตาม Log API ---
        extractedText = firstItem['script']?.toString() ?? "";
      }
    }

    // 3. จัดการ audioUrl: ตรวจสอบข้อมูลจาก Key 'audio' (ถ้ามี)
    final dynamic audioField = json['audio'];
    String? audioUrl;

    if (audioField != null &&
        audioField.toString().trim().isNotEmpty &&
        audioField.toString() != "null") {
      audioUrl = audioField.toString();
    } else {
      audioUrl = null;
    }

    return GenerationResult(
      script: extractedText,
      audioUrl: audioUrl,
      scripts: scriptsList,
    );
  }
}

